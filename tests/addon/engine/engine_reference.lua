-- Builds the engine's own long-run weights per fixture, the basis of the coverage check
-- (fixture_runner.lua --coverage-ref engine, MODEL-06d T1).
--
-- Per fixture it runs BATCHES stratified batches of STRATA fights through the evaluate's own
-- plan (Contract.begin), batch k on REF_SEED + k, the base run and every simulated stat at
-- its +step. A stat's weight is the mean of its batch means and its se their spread over
-- sqrt(BATCHES). A pathwise stat's batch mean is the base run's per-fight slope; a zero stat
-- is 0. The result goes to tests/addon/engine/data/engine_reference.lua with the seed and the
-- fight count.
--
-- Usage: lua tests/addon/engine/engine_reference.lua [BATCHES] [--only ID] [--out PATH]

local Harness = dofile((arg[0]:gsub("[^/\\]+$", "")) .. "harness.lua")
local ns = Harness.load()
local Compare = dofile(Harness.root .. "/tests/addon/engine/compare.lua")

local REF_SEED = 9000000
local STRATA = 199

local batches, only = 80, nil
local out = Harness.root .. "/tests/addon/engine/data/engine_reference.lua"
local i = 1
while i <= #arg do
  if arg[i] == "--only" then only = arg[i + 1] i = i + 1
  elseif arg[i] == "--out" then out = arg[i + 1] i = i + 1
  else batches = tonumber(arg[i]) end
  i = i + 1
end
assert(batches and batches >= 40, "at least 40 batches")

local function mean(values, n)
  local sum = 0
  for k = 1, n do sum = sum + values[k] end
  return sum / n
end

local function meanSe(values)
  local n = #values
  local m, sq = mean(values, n), 0
  for k = 1, n do sq = sq + (values[k] - m) ^ 2 end
  return m, math.sqrt(sq / (n - 1) / n)
end

local ref = Compare.loadReference()
local lines = {
  "-- Generated by tests/addon/engine/engine_reference.lua. Do not edit by hand.",
  "-- The engine's long-run weights per fixture: stratified batches through the evaluate's plan.",
  "return {",
  string.format("  seed = %d, -- batch k runs on seed + k", REF_SEED),
  string.format("  batches = %d,", batches),
  string.format("  strata = %d,", STRATA),
  string.format("  fights = %d, -- per run (base and each simulated stat)", batches * STRATA),
  string.format("  delta = %d,", ref.delta),
  "  cases = {",
}
local t0 = os.clock()
for _, id in ipairs(Harness.FIXTURES) do
  if not only or only == id then
    local scenario = Harness.scenario(id)
    scenario.seed, scenario.weightDelta, scenario.capWindow, scenario.path = REF_SEED, ref.delta, -1, "event"
    local st = ns.Engine.Contract.begin(Harness.snapshots[id], scenario)
    local plan, steps = st.plan, st.steps
    local means, dps = {}, {}
    for _, stat in ipairs(st.stats) do means[stat] = {} end
    for k = 1, batches do
      local seed = REF_SEED + k
      local base, pw = plan.run(nil, seed, STRATA, 1, STRATA)
      dps[k] = mean(base, STRATA)
      for _, stat in ipairs(st.stats) do
        local kind = plan.kinds[stat]
        if kind == "pathwise" then
          means[stat][k] = mean(pw[stat], STRATA)
        elseif kind == "simulated" then
          local plus = plan.run(stat, seed, STRATA, 1, STRATA)
          local sum = 0
          for f = 1, STRATA do sum = sum + (plus[f] - base[f]) / steps[stat] end
          means[stat][k] = sum / STRATA
        else
          means[stat][k] = 0
        end
      end
    end
    local d, dse = meanSe(dps)
    lines[#lines + 1] = string.format('    ["%s"] = {', id)
    lines[#lines + 1] = string.format("      dps = %.17g, dpsSe = %.17g,", d, dse)
    lines[#lines + 1] = "      weights = {"
    local report = {}
    for _, stat in ipairs(st.stats) do
      local w, se = meanSe(means[stat])
      lines[#lines + 1] = string.format('        %s = { weight = %.17g, se = %.17g, kind = "%s" },', stat, w, se,
        plan.kinds[stat])
      report[#report + 1] = string.format("%s %.5f se %.5f", stat, w, se)
    end
    lines[#lines + 1] = "      },"
    lines[#lines + 1] = "    },"
    print(string.format("%s  dps %.2f se %.2f  %s  (%.0f s)", id, d, dse, table.concat(report, ", "),
      os.clock() - t0))
  end
end
lines[#lines + 1] = "  },"
lines[#lines + 1] = "}"
local fh = assert(io.open(out, "wb"))
fh:write(table.concat(lines, "\n"), "\n")
fh:close()
print(string.format("wrote %s: %d batches of %d fights from seed %d + k, %d fights per run", out, batches,
  STRATA, REF_SEED, batches * STRATA))

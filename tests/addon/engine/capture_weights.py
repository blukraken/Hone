#!/usr/bin/env python3
"""Captures MythicSim's pooled stat-weight samples into a committed Lua data file.

Writes tests/addon/engine/data/weights_mythicsim.lua.

For each fixture the request is prepared once as it stands and once per weighed stat with
bonusStats raised by DELTA. Each prepared input then runs with SEEDS seeds. One seed gives one
weight sample per stat: (dps_plus - dps_base) / DELTA, base and plus on the same seed, which is
how the fixtures derive their weights. Seed k is BASE_SEED + k * SEED_STRIDE, because MythicSim
seeds fight i with seed + i. Seed 0 is the fixtures' own seed.

Usage  python3 tests/addon/engine/capture_weights.py [--seeds N] [--iterations N] [--jobs N]
Needs  third_party/mythicsim-forever-engine built at the pin.
"""

import json
import os
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import capture_mythicsim as cm  # noqa: E402

FIXTURE_IDS = [
    "enh60-rockbiter-2h38-hitcap",
    "enh60-rockbiter-2h38-vs60",
    "enh60-rockbiter-dw29-hit97",
    "enh60-windfury-dw20-29",
    "enh60-windfury-dw26-29",
]
STAT_ORDER = ["strength", "agility", "intellect", "attack_power", "hit_rating", "crit_rating",
              "haste_rating"]
DELTA = 100
BASE_SEED = 42


def fixture_request(fid):
    with open(os.path.join(cm.FIXTURES, fid + ".json"), encoding="utf-8") as fh:
        return json.load(fh)["input"]["request"]


def prepare_variants(fid, tmp):
    """Prepared inputs by variant name: "base" and one per weighed stat."""
    request = fixture_request(fid)
    out = {}
    for name in ["base"] + STAT_ORDER:
        req = request if name == "base" else cm.with_bonus(request, cm.STATS[name][0], DELTA)
        prepared, _ = cm.prepare(req, tmp, "%s.%s" % (fid, name))
        out[name] = prepared
    return out


def sim_dps(prepared, seed, iterations, tmp, tag):
    prepared = json.loads(json.dumps(prepared))
    prepared["sim"]["seed"] = seed
    prepared["sim"]["iterations"] = iterations
    prepared["sim"]["debug_first_iteration"] = False
    prep_path = os.path.join(tmp, tag + ".prepared.json")
    out_path = os.path.join(tmp, tag + ".result.json")
    with open(prep_path, "w", encoding="utf-8") as fh:
        json.dump(prepared, fh)
    cm.run([cm.EXE, "sim", "--infile", prep_path, "--gate", "--outfile", out_path])
    with open(out_path, encoding="utf-8") as fh:
        result = json.load(fh)["result"]
    os.remove(prep_path)
    os.remove(out_path)
    return result["raidMetrics"]["dps"]["avg"]


def main():
    argv = sys.argv[1:]

    def opt(name, default):
        return int(argv[argv.index(name) + 1]) if name in argv else default

    seeds = opt("--seeds", 60)
    iterations = opt("--iterations", 3000)
    jobs = opt("--jobs", 8)
    version = cm.run([cm.EXE, "version"]).strip()
    pin = cm.run(["git", "-C", cm.CHECKOUT, "rev-parse", "HEAD"]).strip()

    cases = {}
    with tempfile.TemporaryDirectory() as tmp:
        for fid in FIXTURE_IDS:
            variants = prepare_variants(fid, tmp)
            seed_list = [BASE_SEED + k * cm.SEED_STRIDE for k in range(seeds)]
            tasks = [(name, k) for name in variants for k in range(seeds)]

            def work(task):
                name, k = task
                return task, sim_dps(variants[name], seed_list[k], iterations, tmp,
                                     "%s.%s.%d" % (fid, name, k))

            dps = {name: [None] * seeds for name in variants}
            with ThreadPoolExecutor(max_workers=jobs) as pool:
                for (name, k), value in pool.map(work, tasks):
                    dps[name][k] = value
            cases[fid] = {
                "seeds": seed_list,
                "base": dps["base"],
                "plus": {stat: dps[stat] for stat in STAT_ORDER},
            }
            means = {stat: sum((p - b) / DELTA for p, b in zip(dps[stat], dps["base"])) / seeds
                     for stat in STAT_ORDER}
            print("%-28s seeds %d  base dps seed0 %.6f  mean weights %s" % (
                fid, seeds, dps["base"][0],
                " ".join("%s=%.5f" % (s, means[s]) for s in STAT_ORDER)))

    head = ("-- Generated by tests/addon/engine/capture_weights.py. Do not edit by hand.\n"
            "-- MythicSim %s at %s.\n" % (version, pin))
    cm.write_lua(os.path.join(cm.OUT_DIR, "weights_mythicsim.lua"), head, {
        "engine": version,
        "pin": pin,
        "delta": DELTA,
        "iterations": iterations,
        "stats": STAT_ORDER,
        "cases": cases,
    })


if __name__ == "__main__":
    main()
